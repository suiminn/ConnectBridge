#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES: the license texts of librespot and of every Rust crate that ends up
in the iOS build of librespot (normal and build dependencies for aarch64-apple-ios).

Identical license texts are written once and shared by the crates that carry them.
Run after scripts/build-librespot.sh (it needs build/librespot-src and cargo in the PATH).
"""
import glob, hashlib, json, os, subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "build", "librespot-src")
FEATURES = "native-tls,rodio-backend,with-libmdns"

meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--filter-platform", "aarch64-apple-ios",
     "--no-default-features", "--features", FEATURES],
    cwd=SRC, stderr=subprocess.DEVNULL))

packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}

# Walk the dependency graph from the librespot binary, skipping dev dependencies.
seen, stack = set(), [meta["resolve"]["root"]]
while stack:
    pid = stack.pop()
    if pid in seen:
        continue
    seen.add(pid)
    for dep in nodes[pid]["deps"]:
        if {k["kind"] for k in dep["dep_kinds"]} <= {"dev"}:
            continue
        stack.append(dep["pkg"])

workspace = set(meta["workspace_members"])
external = sorted((packages[p] for p in seen if p not in workspace), key=lambda p: (p["name"], p["version"]))


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read().strip()


def license_files(pkg):
    directory = os.path.dirname(pkg["manifest_path"])
    found = set()
    for pattern in ("LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "UNLICENSE*", "MPL-2.0*", "*-LICENSE*", "*-LICENCE*",
                    "Apache-2.0*", "MIT*.txt", "BSD*.txt", "Zlib*", "Unicode*"):
        found.update(glob.glob(os.path.join(directory, pattern)))
    # priority-queue ships LGPL-3.0-or-later and MPL-2.0 ("or"): MPL-2.0 is the one we use.
    return sorted(p for p in found if os.path.isfile(p) and "LGPL" not in os.path.basename(p))


# text -> (id, [crates]); the first crate that carries a text provides the heading
texts, order = {}, []
per_crate = {}
for pkg in external:
    files = [read(p) for p in license_files(pkg)]
    ids = []
    for text in files:
        key = hashlib.sha256(text.encode()).hexdigest()
        if key not in texts:
            texts[key] = {"text": text, "crates": []}
            order.append(key)
        texts[key]["crates"].append(f"{pkg['name']} {pkg['version']}")
        ids.append(key)
    per_crate[(pkg["name"], pkg["version"])] = ids

out = []
out.append("THIRD-PARTY NOTICES\n===================\n")
out.append("ConnectBridge itself is MIT licensed (see LICENSE). The ConnectBridge package also contains\n"
           "librespot (patched, see librespot/ios-bridge.patch) and the Rust crates listed below.\n"
           "Generated by scripts/gen-third-party-notices.py.\n")

out.append("\n" + "=" * 78 + "\nlibrespot (MIT)  https://github.com/librespot-org/librespot\n" + "=" * 78 + "\n")
lp = os.path.join(SRC, "LICENSE")
out.append(read(lp) if os.path.exists(lp) else "(LICENSE file not found)")

mpl = [p for p in external if "MPL-2.0" in (p.get("license") or "")]
out.append("\n\n" + "=" * 78 + "\nMozilla Public License 2.0 components\n" + "=" * 78 + "\n")
out.append("The following crates are licensed under the Mozilla Public License 2.0. They are used unmodified.\n"
           "Their source code is available from the locations below (and from https://crates.io/crates/<name>/<version>);\n"
           "the license text is included further down (see \"Mozilla Public License Version 2.0\").\n")
for p in mpl:
    out.append(f"  {p['name']} {p['version']}  {p.get('repository') or 'https://crates.io/crates/' + p['name']}")

out.append("\n\n" + "=" * 78 + "\nCrates in the build\n" + "=" * 78 + "\n")
for pkg in external:
    authors = ", ".join(pkg.get("authors") or [])
    line = f"{pkg['name']} {pkg['version']}  --  {pkg.get('license') or 'see license text'}"
    if authors:
        line += f"\n    {authors}"
    out.append(line)

out.append("\n\n" + "=" * 78 + "\nLicense texts (each distinct text once, with the crates that carry it)\n" + "=" * 78)
for key in order:
    entry = texts[key]
    crates = entry["crates"]
    shown = ", ".join(crates[:12]) + (f", ... ({len(crates)} crates)" if len(crates) > 12 else "")
    out.append(f"\n\n--- {shown}\n\n{entry['text']}")

with open(os.path.join(ROOT, "THIRD_PARTY_NOTICES"), "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")

no_file = [p["name"] for p in external if not per_crate[(p["name"], p["version"])]]
print(f"{len(external)} crates, {len(order)} distinct license texts")
print(f"{len(no_file)} crates without a license file (listed with license id and authors): {', '.join(no_file)}")
